/* GameData as given on the command line; "" when the data came from discovery (payload / data dir). */
static const char *gamedata_arg(void)
{ return harness_opts()->gamedata ? harness_opts()->gamedata : fs_mounted() ? "" : NULL; }

static int st_formats(void)
{
    const char *g = gamedata_arg();
    return g ? fmt_selftest(g) : HARNESS_SELFTEST_ABSENT;
}

static int st_audio(void)
{
    const char *g = gamedata_arg();
    if (!g) return HARNESS_SELFTEST_ABSENT;
    Scratch s = mem_scratch_begin(NULL);
    const char *wav = str_cat_arena(s.arena, sav_dir(), "selftest.wav", NULL);   /* never the cwd */
    const char *koe = str_cat_arena(s.arena, ref_dir(), "/wp5_koe_numbers.tsv", NULL);
    int rc = audio_selftest_ex(g, wav, plat_path_is_file(koe) ? koe : NULL);
    mem_scratch_end(&s);
    return rc;
}

/* The save round trip needs live VM/proc state: start the VM on the first scene when a Scene.pck is loaded. */
static int st_save(void)
{
    if (harness_pack() && harness_pack()->nscene > 0 && vm_init(harness_pack()))
        (void)vm_start(0, 0); /* scene 0 exists */
    return sav_selftest();
}

static const char *verdict(int rc) { return rc == 0 ? "PASS" : rc == HARNESS_SELFTEST_ABSENT ? "SKIP" : "FAIL"; }

int harness_selftest_assets(void)
{
    print_scene_counts();   /* WP7-side independent counts (§4 M0), then the owners' detailed selftests */
    print_gameexe();
    selftest_g00();
    print_cgm();
    (void)fflush(stdout);   /* keep our lines before the owners' output */
    int rc_f = st_formats();
    (void)fflush(stdout);
    int rc_a = st_audio();
    (void)fflush(stdout);
    printf("SELFTEST formats %s\nSELFTEST audio %s\n", verdict(rc_f), verdict(rc_a));
    if ((rc_f && rc_f != HARNESS_SELFTEST_ABSENT) || (rc_a && rc_a != HARNESS_SELFTEST_ABSENT)) return 1;
    return rc_f || rc_a ? HARNESS_SELFTEST_ABSENT : 0;
}

static bool list_has(const char *list, const char *name)
{
    Str rest = str_c(list), field;
    while (str_split(&rest, ',', &field)) {   /* bounded by the list length */
        if (str_eq_fold(field, str_c(name))) return true;
        if (!rest.n) break;
    }
    return false;
}

int harness_selftest(const char *list)
{
    static const struct { const char *name; int (*fn)(void); } T[] = {
        { "core", core_selftest }, { "formats", st_formats }, { "gfx", gfx_selftest }, { "text", txt_selftest },
        { "audio", st_audio }, { "ui", ui_selftest }, { "save", st_save },
    };
    bool all = !list || !*list || str_eq_fold(str_c(list), STR("all"));
    int fails = 0, skips = 0;
    for (size_t i = 0; i < COUNT_OF(T); i++) {
        if (!all && !list_has(list, T[i].name)) continue;
        printf("== %s\n", T[i].name);
        (void)fflush(stdout);
        int rc = T[i].fn();
        (void)fflush(stdout);
        printf("SELFTEST %s %s\n", T[i].name, verdict(rc));
        if (rc == HARNESS_SELFTEST_ABSENT) skips++;
        else if (rc) fails++;
    }
    printf("SELFTEST summary: %d failed, %d skipped\n", fails, skips);
    return fails ? 1 : 0;
}
