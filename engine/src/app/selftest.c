/* ref line: name \t cut \t w \t h \t crc32 (hex), generated by tests/gen_wp7_g00_crc.py */
typedef struct { Str name; int cut, w, h; uint32_t crc; } CrcRef;
typedef struct { CrcRef *v; int n; } CrcTable;

static bool parse_hex32(Str s, uint32_t *out)
{
    uint32_t v = 0;
    if (s.n == 0 || s.n > 8) return false;
    for (size_t i = 0; i < s.n; i++) {
        char c = s.p[i];
        int d = c >= '0' && c <= '9'   ? c - '0'
                : c >= 'a' && c <= 'f' ? c - 'a' + 10
                : c >= 'A' && c <= 'F' ? c - 'A' + 10
                                       : -1;
        if (d < 0) return false;
        v = v << 4 | (uint32_t)d;
    }
    *out = v;
    return true;
}

static bool parse_crc_line(Str line, CrcRef *r)
{
    int v[3];
    Str rest = line;
    r->name = str_next_token(&rest);
    for (int k = 0; k < 3; k++) {
        Str t = str_next_token(&rest);
        if (str_scan_ints(t, &v[k], 1) != 1) return false;
    }
    r->cut = v[0]; r->w = v[1]; r->h = v[2];
    return r->name.n && r->name.n <= CRC_NAME_MAX && line.p[0] != '#' && parse_hex32(str_next_token(&rest), &r->crc);
}

static int crc_ref_cmp(const void *a, const void *b)
{
    const CrcRef *x = a, *y = b;
    int c = str_cmp_fold(x->name, y->name);
    return c ? c : (x->cut > y->cut) - (x->cut < y->cut);
}

/* The reference table, sorted for bsearch; empty when the file is missing. Lives in `ar`. */
static CrcTable load_crc_ref(Arena *ar, const char *path)
{
    CrcTable t = { NULL, 0 };
    size_t len;
    const char *d = (const char *)plat_read_file_arena(ar, path, HARNESS_REF_MAX, &len);
    if (!d) return t;
    size_t lines = 1;
    for (size_t i = 0; i < len; i++) lines += d[i] == '\n';
    t.v = ARENA_NEW_ARRAY(ar, CrcRef, lines);
    Str rest = str_make(d, len), line;
    while (str_split(&rest, '\n', &line) && (size_t)t.n < lines)
        if (parse_crc_line(str_trim(line), &t.v[t.n])) t.n++;
    qsort(t.v, (size_t)t.n, sizeof *t.v, crc_ref_cmp);
    return t;
}

/* CRC over the BGRA bytes (little-endian 0xAARRGGBB) of the full cut canvas, as g00.py's PNG. */
static uint32_t cut_crc(const G00Cut *cut, Arena *ar)
{
    ArenaMark m = arena_mark(ar);
    uint8_t *row = arena_alloc_uninit(ar, (size_t)cut->w * 4, 4);
    uint32_t crc = 0;
    for (int y = 0; y < cut->h; y++) {
        const uint32_t *px = cut->px + (size_t)y * (size_t)cut->w;
        for (int x = 0; x < cut->w; x++) bin_store_le32(row + (size_t)x * 4, px[x]);
        crc = hash_crc32(crc, row, (size_t)cut->w * 4);
    }
    arena_reset_to(ar, m);
    return crc;
}

typedef struct {
    int decoded, types[3], slots, nonempty, slots2, nonempty2, crc_ok, crc_bad, crc_missing;
} G00Stats;

static void check_cut(const CrcTable *ref, Str base, int c, const G00Cut *cut, Arena *ar, G00Stats *st)
{
    uint32_t crc = cut_crc(cut, ar);
    CrcRef key = { base, c, 0, 0, 0 };
    const CrcRef *hit = bsearch(&key, ref->v, (size_t)ref->n, sizeof *ref->v, crc_ref_cmp);
    if (!hit) { st->crc_missing++; return; }
    if (hit->crc == crc && hit->w == cut->w && hit->h == cut->h) { st->crc_ok++; return; }
    if (st->crc_bad < 10)
        printf("  g00 crc mismatch %.*s cut %d (%dx%d crc %08x, ref %dx%d %08x)\n", (int)base.n, base.p, c, cut->w,
               cut->h, crc, hit->w, hit->h, hit->crc);
    st->crc_bad++;
}

static void g00_file_stats(const char *file, const CrcTable *ref, Arena *ar, G00Stats *st)
{
    const char *path = str_cat_arena(ar, "g00/", file, NULL);
    size_t len;
    uint8_t *d = fs_read_all(path, &len);
    G00 *g = d ? g00_decode(d, len) : NULL;
    fs_free(d);
    if (!g) return;
    st->decoded++;
    if (g->type >= 0 && g->type <= 2) st->types[g->type]++;
    st->slots += g->ncut;
    if (g->type == 2) st->slots2 += g->ncut;
    Str base = str_c(file);
    size_t dot;
    if (str_rfind_char(base, '.', &dot)) base = str_sub(base, 0, dot);
    for (int c = 0; c < g->ncut; c++) {
        const G00Cut *cut = &g->cut[c];
        if (!cut->px) continue;
        st->nonempty++;
        if (g->type == 2) st->nonempty2++;
        if (ref->v) check_cut(ref, base, c, cut, ar, st);
    }
    g00_free(g);
}

static void selftest_g00(void)
{
    char **files = NULL;
    int nfiles = fs_list("g00", "g00", &files);   /* layered fs: GameData dir or payload */
    Scratch s = mem_scratch_begin(NULL);
    const char *refpath = str_cat_arena(s.arena, ref_dir(), "/wp7_g00_crc.tsv", NULL);
    CrcTable ref = load_crc_ref(s.arena, refpath);
    G00Stats st;
    memset(&st, 0, sizeof st);
    for (int i = 0; i < nfiles; i++) {
        ArenaMark m = arena_mark(s.arena);
        g00_file_stats(files[i], &ref, s.arena, &st);
        arena_reset_to(s.arena, m);
    }
    /* §4 M0 counts type-2 index slots (2840) and their real cuts (2315); type 0/1 add one cut each */
    printf("M0 g00 files=%d decoded=%d types=%d/%d/%d type2_slots=%d type2_nonempty=%d cuts_all=%d nonempty_all=%d",
           nfiles, st.decoded, st.types[0], st.types[1], st.types[2], st.slots2, st.nonempty2, st.slots, st.nonempty);
    if (ref.v) printf(" crc_ok=%d crc_bad=%d crc_missing=%d (ref %d)\n", st.crc_ok, st.crc_bad, st.crc_missing, ref.n);
    else printf(" crc=noref (%s)\n", refpath);
    mem_scratch_end(&s);
    fs_list_free(files, nfiles);
}

static void print_gx_line(const char *key, int nints)
{
    printf(" %s=", key);
    for (int i = 0; i < nints; i++) printf("%s%d", i ? "," : "", gx_int(key, i, -9999));
}

static void print_utf8(const char *before, const WStr *s, const char *after)
{
    Scratch sc = mem_scratch_begin(NULL);
    printf("%s%s%s", before, ws_utf8_arena(sc.arena, s, WS_UTF8_SHORT_MAX), after);
    mem_scratch_end(&sc);
}

static void print_scene_counts(void)
{
    if (!harness_pack()) return;
    printf("M0 scenes=%d inc_cmd=%d\n", harness_pack()->nscene, harness_pack()->ninc_cmd);
    WStr s101 = { 0 }, t = { 0 };
    ws_set_utf8(&s101, "seen101");
    int i101 = pack_find_scene(harness_pack(), &s101);
    if (i101 >= 0) {
        scene_str(&harness_pack()->scene[i101], 0, &t);
        print_utf8("M0 seen101_str0=", &t, "\n");
    }
    ws_free(&t);
    ws_free(&s101);
}

static void print_gameexe(void)
{
    printf("M0 gameexe");
    print_gx_line("MWND.002.MOJI_SIZE", 1);
    print_gx_line("MWND.002.MOJI_CNT", 2);
    int tup[64];
    printf(" SHAKE.002_ints=%d", gx_tuples("SHAKE.002", tup, (int)COUNT_OF(tup)));
    WStr b0 = { 0 }, b1 = { 0 };
    bool h0 = gx_str("BGM.001", 0, &b0), h1 = gx_str("BGM.001", 1, &b1);
    print_utf8(" BGM.001=\"", h0 ? &b0 : NULL, "\"");
    print_utf8(",\"", h1 ? &b1 : NULL, "\"");
    printf(",%d,%d,%d", gx_int("BGM.001", 2, -1), gx_int("BGM.001", 3, -1), gx_int("BGM.001", 4, -1));
    ws_free(&b0);
    ws_free(&b1);
    print_gx_line("FLAG.CNT", 1);
    printf("\n");
}

static void print_cgm(void)
{
    int ncg = cgt_count(), maxflag = -1;
    for (int i = 0; i < ncg; i++) {
        const char *nm = cgt_name(i);
        int f = nm ? cgt_flag_no(nm) : -1;
        if (f > maxflag) maxflag = f;
    }
    const char *first = ncg > 0 ? cgt_name(0) : NULL;
    printf("M0 cgm entries=%d first=%s flag0=%d flag_max=%d\n", ncg, first ? first : "-",
           first ? cgt_flag_no(first) : -1, maxflag);
}

