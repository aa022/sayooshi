enum {
    HARNESS_REF_MAX = 8 << 20,           /* bytes of a selftest reference table */
    CRC_NAME_MAX = 63                    /* g00 base names in wp7_g00_crc.tsv */
};

/* tests/ref: $SAYO_REF_DIR, $SAYOOSHI_REF_DIR, <this file>/../../tests/ref, ./engine/tests/ref, ./tests/ref. Kept in
 * the perm arena after the first call. */
static const char *ref_dir(void)
{
    static const char *dir;
    if (dir) return dir;
    const char *env = SDL_getenv("SAYO_REF_DIR");
    if (!env || !*env) env = SDL_getenv("SAYOOSHI_REF_DIR");
    if (env && *env) return dir = arena_strdup(mem_perm(), env);
    Scratch s = mem_scratch_begin(NULL);
    Str src_dir = path_dir(str_c(__FILE__));
    const char *src_ref =
        src_dir.n ? str_cat_arena(s.arena, str_dup_arena(s.arena, src_dir), "/../../tests/ref", NULL) : NULL;
    const char *cand[3] = { src_ref, "engine/tests/ref", "tests/ref" };
    for (int i = 0; i < 3 && !dir; i++)
        if (cand[i] && plat_path_is_dir(cand[i])) dir = arena_strdup(mem_perm(), cand[i]);
    mem_scratch_end(&s);
    if (!dir) dir = "engine/tests/ref";
    return dir;
}

