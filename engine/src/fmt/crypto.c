void crypto_xor_cycle(uint8_t *d, size_t n, const uint8_t *key, size_t klen, size_t start)
{
    if (!klen) return;
    size_t k = start % klen;
    for (size_t i = 0; i < n; i++) {
        d[i] ^= key[k];
        if (++k == klen) k = 0;
    }
}

